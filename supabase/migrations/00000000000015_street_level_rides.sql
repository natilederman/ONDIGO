create table demo_places (
  id serial primary key,
  city text not null,
  state text not null,
  line1 text not null,   -- exact: "1234 Valencia Street"
  block text not null,   -- public: "1200 block of Valencia St, San Francisco, CA"
  lat double precision not null,
  lng double precision not null
);
create index demo_places_city_idx on demo_places (state, city);

-- the cities that get in-city rides, weighted roughly by size
create table demo_metros (city text not null, state text not null, weight numeric not null, primary key (state, city));

