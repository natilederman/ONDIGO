-- ---------------------------------------------------------------------------
-- Street-level rides.
--
-- Until now every demo request ran city to city, which says little when one
-- side of a city is an hour from the other. From here each end is a street
-- address, shown in public by its block only:
--
--   members see      "1200 block of Valencia St, San Francisco, CA"
--   matched driver   gets the exact number from request_contact_details
--   visitors         see the city, through map_public_activity (0.1 degree)
--
-- The demo now keeps two kinds of ride on the map: long rides between cities
-- (mostly across a state line, a few long ones inside a state such as
-- Los Angeles to San Francisco) and rides that start and end inside one city.
-- Prices fall in three bands by distance, then move with size and weight:
--
--   inside a city            $15 to $60
--   city to city, one state  $60 to $180
--   across a state line      $150 to $600, more for bulky items
--
-- The addresses are real public business addresses from OpenStreetMap
-- (shops, cafes, libraries), never homes. Coordinates are rounded to three
-- decimals, about a block.
-- ---------------------------------------------------------------------------

