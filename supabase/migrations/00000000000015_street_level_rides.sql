-- great-circle distance in km
create or replace function demo_km(a_lat double precision, a_lng double precision, b_lat double precision, b_lng double precision)
returns numeric language sql immutable as $$
  select (6371 * acos(least(1, cos(radians(a_lat)) * cos(radians(b_lat)) * cos(radians(b_lng - a_lng))
                                + sin(radians(a_lat)) * sin(radians(b_lat)))))::numeric
$$;

-- the three bands; inside each, distance, weight and size move the price
create or replace function demo_price(p_band text, p_km numeric, p_kg numeric, p_size text)
returns numeric language sql immutable as $$
  select case p_band
    when 'local' then
      least(60, greatest(15, round(15 + 2.2 * p_km + 0.6 * p_kg
        + case p_size when 'large' then 12 when 'medium' then 5 else 0 end)))
    when 'state' then
      least(180, greatest(60, round((60 + 0.17 * p_km + 1.0 * p_kg
        + case p_size when 'large' then 30 when 'medium' then 10 else 0 end) / 5) * 5))
    else
      least(case when p_size = 'large' and p_kg >= 30 then 900 when p_size = 'large' then 700 else 600 end,
        greatest(150, round((150 + 0.13 * p_km + 1.6 * p_kg
          + case p_size when 'large' then 60 when 'medium' then 20 else 0 end) / 5) * 5))
  end
$$;

drop function if exists demo_refill();
create function demo_refill() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_senders uuid[] := array[
    '33333333-3333-3333-3333-333333333333', '88888888-8888-8888-8888-888888888888',
    '77777777-7777-7777-7777-777777777777', '55555555-5555-5555-5555-555555555555',
    '11111111-1111-1111-1111-111111111111'
  ]::uuid[];
  v_demo uuid[] := v_senders || array['22222222-2222-2222-2222-222222222222', '44444444-4444-4444-4444-444444444444', '66666666-6666-6666-6666-666666666666']::uuid[];
  v_local_notes text[] := array['Across town this afternoon, room on the back seat.', 'Doing a run through the city, can take a box or two.',
                                'Courier loop, back by evening.', 'Heading across town after work.'];
  v_long_notes text[] := array['Leaving early, back the next day.', 'Room in the back, happy to carry.',
                               'Regular run, can take a few things.', 'Driving down for the weekend.'];
  v_share numeric := coalesce(setting_num('demo_same_state_share'), 0.2);
  v_need jsonb; v_added jsonb := '{}'::jsonb;
  v_retired_r integer := 0; v_retired_t integer := 0;
  k text; n integer; i integer; v_local boolean; v_trip boolean; v_same boolean;
  r demo_routes%rowtype; m demo_metros%rowtype; it demo_items%rowtype; d demo_drivers%rowtype;
  a demo_places%rowtype; b demo_places%rowtype;
  v_km numeric; v_band text; v_price numeric; v_auction boolean; v_id uuid;
begin
  if coalesce(setting_num('demo_refill_enabled'), 1) = 0 then return jsonb_build_object('skipped', true); end if;

  -- retire stale demo rows: fixed-price requests past their date, trips that left over a day ago
  update delivery_requests set status = 'cancelled'
  where status = 'open' and sender_id = any(v_demo) and needed_by < current_date;
  get diagnostics v_retired_r = row_count;
  update trips set status = 'completed'
  where status = 'active' and driver_id = any(v_demo) and depart_at < now() - interval '1 day';
  get diagnostics v_retired_t = row_count;

  -- what is missing of each kind; a ride under 25 km end to end counts as in-city, as on the map
  select jsonb_build_object(
    'long_requests', greatest(0, setting_num('demo_long_requests')::integer
      - count(*) filter (where demo_km(pickup_lat, pickup_lng, dropoff_lat, dropoff_lng) >= 25)),
    'local_requests', greatest(0, setting_num('demo_local_requests')::integer
      - count(*) filter (where demo_km(pickup_lat, pickup_lng, dropoff_lat, dropoff_lng) < 25)))
  into v_need from delivery_requests where status = 'open';
  select v_need || jsonb_build_object(
    'long_trips', greatest(0, setting_num('demo_long_trips')::integer
      - count(*) filter (where demo_km(origin_lat, origin_lng, destination_lat, destination_lng) >= 25)),
    'local_trips', greatest(0, setting_num('demo_local_trips')::integer
      - count(*) filter (where demo_km(origin_lat, origin_lng, destination_lat, destination_lng) < 25)))
  into v_need from trips where status = 'active' and depart_at > now() - interval '1 day';

  foreach k in array array['long_requests', 'local_requests', 'long_trips', 'local_trips'] loop
    n := (v_need ->> k)::integer;
    v_local := k like 'local%';
    v_trip := k like '%trips';
    for i in 1 .. n loop
      if v_local then
        -- a weighted city, then two of its addresses a little way apart
        select * into m from demo_metros order by -ln(random()) / weight limit 1;
        select * into a from demo_places where city = m.city and state = m.state order by random() limit 1;
        select * into b from demo_places
          where city = m.city and state = m.state and id <> a.id and demo_km(lat, lng, a.lat, a.lng) between 1.2 and 14
          order by random() limit 1;
        continue when b.id is null;
        v_band := 'local';
      else
        -- mostly across a state line; now and then a long ride inside one state
        v_same := random() < v_share;  -- drawn once, not per row
        select * into r from demo_routes where (from_state = to_state) = v_same order by random() limit 1;
        if random() < 0.5 then
          select * into a from demo_places where city = r.from_city and state = r.from_state order by random() limit 1;
          select * into b from demo_places where city = r.to_city and state = r.to_state order by random() limit 1;
        else
          select * into a from demo_places where city = r.to_city and state = r.to_state order by random() limit 1;
          select * into b from demo_places where city = r.from_city and state = r.from_state order by random() limit 1;
        end if;
        continue when a.id is null or b.id is null;
        v_band := case when r.from_state = r.to_state then 'state' else 'cross' end;
      end if;
      v_km := demo_km(a.lat, a.lng, b.lat, b.lng);

      if v_trip then
        select * into d from demo_drivers where v_local or vehicle <> 'bike' order by random() limit 1;
        insert into trips (driver_id, origin_text, origin_lat, origin_lng, destination_text, destination_lat, destination_lng,
                           depart_at, vehicle_type, capacity_weight_kg, capacity_size, notes)
        values (
          d.driver_id, a.block, a.lat, a.lng, b.block, b.lat, b.lng,
          now() + make_interval(hours => case when v_local then 2 + floor(random() * 70) else 6 + floor(random() * 160) end::integer),
          d.vehicle, d.capacity_kg, d.capacity_size,
          case when v_local then v_local_notes[1 + floor(random() * 4)::integer] else v_long_notes[1 + floor(random() * 4)::integer] end
        );
      else
        select * into it from demo_items order by random() limit 1;
        v_price := demo_price(v_band, v_km, it.weight_kg, it.size);
        v_auction := random() < 0.6;
        insert into delivery_requests (
          sender_id, item_description, item_size, item_weight_kg,
          pickup_text, pickup_lat, pickup_lng, dropoff_text, dropoff_lat, dropoff_lng,
          needed_by, pricing_mode, fixed_price, starting_price, current_price, bidding_ends_at,
          extend_on_bid, extend_seconds, fragile, legal_declaration_accepted,
          declared_value, declared_category, contents, open_box_required
        ) values (
          v_senders[1 + floor(random() * array_length(v_senders, 1))::integer], it.item, it.size, it.weight_kg,
          a.block, a.lat, a.lng, b.block, b.lat, b.lng,
          current_date + case when v_local then 1 + floor(random() * 4) else 3 + floor(random() * 8) end::integer,
          case when v_auction then 'auction' else 'fixed' end::pricing_mode,
          case when v_auction then null else v_price end,
          case when v_auction then round(v_price * 1.3) else null end,
          case when v_auction then v_price else null end,
          case when v_auction then now() + make_interval(hours => case when v_local then 2 + floor(random() * 30) else 6 + floor(random() * 90) end::integer) else null end,
          v_auction, 90, it.fragile, true,
          it.value, it.category, it.item, true
        ) returning id into v_id;
        -- the exact door, for the driver who wins it
        insert into request_contact_details (request_id, pickup_line1, dropoff_line1) values (v_id, a.line1, b.line1);
      end if;
      v_added := v_added || jsonb_build_object(k, coalesce((v_added ->> k)::integer, 0) + 1);
    end loop;
  end loop;

  return v_added || jsonb_build_object('requests_retired', v_retired_r, 'trips_retired', v_retired_t);
end;
$$;
